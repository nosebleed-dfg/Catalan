from collections import deque

print("A. Is -I in <T, L_w> inside SL2(Z/2^a)?")
def mul(A, B, m):
    return ((A[0]*B[0] + A[1]*B[2]) % m, (A[0]*B[1] + A[1]*B[3]) % m, (A[2]*B[0] + A[3]*B[2]) % m, (A[2]*B[1] + A[3]*B[3]) % m)
def gen_group(gens, m):
    I = (1, 0, 0, 1); seen = {I}; dq = deque([I])
    while dq:
        x = dq.popleft()
        for g in gens:
            y = mul(x, g, m)
            if y not in seen: seen.add(y); dq.append(y)
    return seen
for a in (2, 3, 4, 5, 6):
    m = 2**a; minusI = (m - 1, 0, 0, m - 1)
    row = []
    for w in range(1, 17):
        G = gen_group([(1, 1, 0, 1), (1, 0, w % m, 1)], m)
        row.append("%d%s" % (w, "+" if minusI in G else "."))
    print("   mod 2^%d: %s" % (a, " ".join(row)))
